test('NOAA/WMO solar geometry: equinox, summer, winter, polar day/night, opposing hemisphere',()=>{
 const text=js;
 const clean=text.match(/function solarGeometry\(latitudeDegrees,declinationDegrees\)\{([\s\S]*?)\n \}/);
 assert.ok(clean,'Calculations absent');
 assert.match(js,/Math\.acos\(cosH\)/);
 assert.match(js,/Math\.tan\(radians\(latitudeDegrees\)\)/);
 assert.match(js,/90-Math\.abs\(latitudeDegrees-declinationDegrees\)/);
 const rad=d=>d*Math.PI/180;
 const evaluateSun=(phi,d)=>{
  const alt=90-Math.abs(phi-d);
  const cost=-Math.tan(rad(phi))*Math.tan(rad(d));
  return {alt,day:cost>=1?0:cost<=-1?24:24*Math.acos(cost)/Math.PI};
 };
 const gdansk=evaluateSun(54.35,23.44);
 assert.ok(Math.abs(gdansk.alt-59.09)<1e-8);
 assert.ok(Math.abs(gdansk.day-16.9589138)<1e-5);
 const equinox=evaluateSun(54.35,0);
 assert.equal(equinox.day,12);
 assert.equal(equinox.alt,35.65);
 assert.equal(evaluateSun(70,23.44).day,24);
 assert.equal(evaluateSun(70,-23.44).day,0);
 assert.ok(evaluateSun(70,-23.44).alt<0);
 const syd=evaluateSun(-33.87,-23.44);
 assert.ok(Math.abs(syd.alt-79.57)<.01);
 assert.ok(Math.abs(syd.day-14.25584)<.0001);
 assert.match(html,/16 h 58 min/);
 assert.match(html,/59,1°/);
 assert.match(html,/data-decl="-23\.44"/);
 assert.match(html,/data-decl="23\.44"/);
});
