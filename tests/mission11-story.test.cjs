'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
test('ATLAS SOLARIS 11: artystyczna oprawa, artykul i zachowane laboratorium',()=>{
 const html=read('etapy/11/index.html');
 assert.match(html,/<article\b/);
 assert.match(html,/<h1\b[^>]*id="m11-title"/);
 assert.match(html,/mission11-cover\.svg/);
 assert.match(html,/mission11-story\.css/);
 assert.match(html,/mission11-story\.js/);
 assert.match(html,/id="m11-map"/);
 assert.match(html,/id="m11-launch"/);
 assert.match(html,/id="m11-flight"/);
 assert.match(html,/data-src="\.\.\/\.\.\/atlas\.html\?portal=porkchop"/);
 assert.match(html,/id="stageFrame"/);
 assert.match(html,/aria-controls="stageInfo"/);
 assert.doesNotMatch(html,/<a[^>]*href="\.\.\/\.\.\/atlas\.html/);
 assert.match(read('portal/mission11-story.css'),/overflow-y:auto!important/);
 const svg=read('portal/media/mission11-cover.svg');
 assert.match(svg,/<svg\b/);
 assert.match(svg,/Ziemi do Marsa/);
 assert.match(svg,/<\/svg>\s*$/);
});
test('ATLAS SOLARIS 11: Lambert, transfer Hohmanna i prawidlowe jednostki',()=>{
 const context={window:{}};
 vm.runInNewContext(read('portal/mission11-story.js'),context,{filename:'mission11-story.js'});
 const model=context.window.ATLAS11_MODEL;
 assert.ok(model,'Model naukowy musi byc dostepny dla testow');
 assert.ok(model.hohmannDays>258&&model.hohmannDays<260);
 assert.ok(model.initialPhaseDegrees>43&&model.initialPhaseDegrees<46);
 const ref=model.solve(0,model.hohmannDays);
 assert.ok(ref && Number.isFinite(ref.c3), 'Transfer referencyjny musi miec rozwiazanie');
 assert.ok(ref.c3>8.4&&ref.c3<9.1, 'C3 Hohmanna powinno wynosic ok. 8,7 km²/s², otrzymano '+ref.c3);
 assert.ok(ref.vinf>2.8&&ref.vinf<3.1, 'v∞ ok. 2,94 km/s');
 assert.ok(ref.arrival>2.5&&ref.arrival<2.9, 'Przybycie ok. 2,65 km/s');
 assert.ok(Math.abs(ref.vinf**2-ref.c3)<1e-8,'C3=v∞²');
 const tooEarly=model.solve(-40,259);
 assert.ok(tooEarly&&tooEarly.c3>ref.c3+3,'Wczesniejszy start jest energetycznie drozszy w tym modelu');
 const expensive=model.solve(70,180);
 assert.ok(expensive&&expensive.c3>ref.c3*4);
 assert.match(model.unit,/km²\/s²/);
});
