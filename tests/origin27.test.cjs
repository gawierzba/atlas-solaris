'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const fixture={};vm.runInNewContext(read('portal/data.js'),{window:fixture});
const data=fixture.ATLAS_PORTAL_DATA;
const json=JSON.parse(read('portal/catalog.json'));
assert.equal(data.version,json.version,'Zapisany katalog i wczytywane trasy muszą mieć tę samą wersję');
const lastStage=Math.max(...Object.values(data.stages).map(x=>x.number));
assert.equal(Object.keys(data.stages).length,lastStage,'Etapy od 1 do '+lastStage+' powinny być kompletne');
for(let n=1;n<=lastStage;n++){
 const key=String(n).padStart(2,'0');
 assert.equal(data.stages[key].number,n,'Brak numeru etapu '+n);
 assert.equal(json.stages[key].number,n,'Katalog JSON bez etapu '+n);
 assert.equal(data.stages[key].path,'etapy/'+key+'/','Nieprawidłowa trasa '+n);
 assert.equal(json.stages[key].path,data.stages[key].path);
 assert.ok(read(data.stages[key].path+'index.html').includes('data-route="'+key+'"'),'Brak działającej podstrony '+n);
}
const stage=data.stages['27'];
assert.equal(stage.milestone,true);
assert.equal(stage.category,'nauka');
assert.equal(stage.src,'opowiesc/narodziny-atlasu/index.html');
assert.match(stage.title,/Narodziny ATLAS SOLARIS/);
assert.match(read('etapy/27/index.html'),/stageFrame/);
assert.match(read('etapy/27/index.html'),/opowiesc\/narodziny-atlasu\/index\.html/);
assert.doesNotMatch(read('etapy/27/index.html'),/<a[^>]*href=[\"'][^\"']*README/i);
assert.ok(read('README_ETAP27.md').length>500,'Pierwotna dokumentacja musi pozostać w repozytorium');
const story=read(stage.src);
assert.match(story,/Przed i po|PRZED I PO/);
assert.match(story,/Sześć kierunków/);
assert.doesNotMatch(story,/<a[^>]*href=[\"'][^\"']*README/i,'Opowieść nie może linkować do plików technicznych');
assert.match(story,/o27Before/);
assert.match(story,/o27After/);
assert.match(read('portal/origin27.js'),/atlas:portal:ready/);
assert.match(read('portal/site.js'),/stage-card--milestone/);
assert.match(read('portal/stage.js'),/orderedStageKeys/);
assert.match(read('README_PORTAL27.md'),/27\.0/);
assert.match(read('index.html'),new RegExp(String(lastStage)+' etap'));
assert.doesNotMatch(read('portal/site.js'),/Brakujące numery oznaczamy osobno/);
console.log('ATLAS SOLARIS 27 · '+lastStage+' etapów bez luk, 27 jako kamień milowy i kompletna nawigacja OK');
