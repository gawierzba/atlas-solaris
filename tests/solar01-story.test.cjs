'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('etapy/01/index.html'),css=read('portal/solar01-story.css'),cover=read('portal/media/solar01-cover.svg');
const shell=read('portal/stage.js'),engine=read('atlas.html'),core=read('js/app.js');
test('First chapter is a full astronomy introduction with verifiable observations and credible sources',()=>{
 for(const word of ['To nie niebo','Mars','Kopernik','Kepler','Galileusz','Newton','Pale Blue Dot','Voyager 1','1990','1543','1687','Merkury','Neptun','jednostka astronomiczna','planetarium'])assert.ok(html.includes(word),'Missing '+word);
 for(const name of ['Merkury','Wenus','Ziemia','Mars','Jowisz','Saturn','Uran','Neptun'])assert.ok(html.includes('<h3>'+name+'</h3>'),name);
 for(const id of ['wprowadzenie','kopernik','planety','grawitacja','blekitny-punkt','laboratorium','zrodla'])assert.ok(html.includes('id="'+id+'"'),id);
 assert.ok(html.indexOf('id="wprowadzenie"')<html.indexOf('id="laboratorium"'));
 assert.ok(html.indexOf('id="blekitny-punkt"')<html.indexOf('id="laboratorium"'));
 assert.ok(html.indexOf('id="laboratorium"')<html.indexOf('id="zrodla"'));
 assert.match(html,/NASA\/JPL-Caltech/);
 assert.match(html,/PIA23645\.jpg/);
 for(const src of ['science.nasa.gov/earth/earth-observatory/planetary-motion/','science.nasa.gov/solar-system/planets/','ssd.jpl.nasa.gov/planets/approx_pos.html','science.nasa.gov/mission/voyager/voyager-1s-pale-blue-dot/'])assert.ok(html.includes(src),'source missing: '+src);
 assert.match(html,/w latach 1800–2050/);
 assert.match(html,/nie są w skali/);
 assert.match(html,/wspólnego środka masy/);
});
test('The first chapter is readable without GPU and photographs are explicitly labelled',()=>{
 assert.match(cover,/<svg/);
 assert.match(cover,/viewBox="0 0 1600 900"/);
 assert.ok(Buffer.byteLength(cover,'utf8')<45000);
 assert.doesNotMatch(cover,/<script|<animate|<animateTransform|<foreignObject|filter=/i);
 assert.match(html,/portal\/media\/solar01-cover\.svg/);
 assert.match(html,/loading="lazy"/);
 assert.match(html,/data-lazy="true" data-manual="true"/);
 assert.match(html,/id="stageStartLab"/);
 assert.match(html,/id="stageLaunch"/);
 assert.match(html,/id="stageLoading"/);
 assert.match(html,/id="stageReload"/);
 assert.match(html,/id="stageRelated"/);
 assert.match(html,/id="stageInfo"/);
 assert.match(html,/id="stageFrame"[^>]*data-src="\.\.\/\.\.\/atlas\.html\?portal=solar"/);
 assert.doesNotMatch(html,/<script[^>]*src=".*three|<canvas|requestAnimationFrame/);
 assert.match(css,/overflow-y:auto/);
 assert.match(css,/@media\(max-width:650px\)/);
 assert.match(css,/@media\(max-width:360px\)/);
});
test('Manual opt-in extends existing lazy shell without changing other stage behaviour',()=>{
 assert.match(shell,/const lazyLab=iframe\?\.dataset\.lazy==='true'/);
 assert.match(shell,/const manualLab=iframe\?\.dataset\.manual==='true'/);
 assert.match(shell,/stageStartLab/);
 assert.match(shell,/if\(manualLab\)/);
 assert.match(shell,/IntersectionObserver/);
 assert.match(shell,/else startLab\(\)/);
 assert.match(shell,/atlas:portal:ready/);
 assert.match(engine,/id="space"/);
 assert.match(engine,/id="speedSelect"/);
 assert.match(engine,/id="timeSlider"/);
 assert.match(engine,/id="planetList"/);
 assert.match(core,/ssd\.jpl\.nasa\.gov\/planets\/approx_pos\.html/);
});
