test('Ziemia, Ksiezyc i ich sredni rozstaw: ten sam przelicznik do pikseli',()=>{
 const earthDiameterKm=12742,moonDiameterKm=3474.8,distanceKm=384400,earthPx=48;
 const moonPx=13.09,earthY=116+24,moonY=1581.52+13.09/2;
 const apparentMoonRatio=moonPx/earthPx;
 const distanceInEarthDiameters=(moonY-earthY)/earthPx;
 assert.ok(Math.abs(apparentMoonRatio-moonDiameterKm/earthDiameterKm)<0.0003,'Zla srednica Ksiezyca');
 assert.ok(Math.abs(distanceInEarthDiameters-distanceKm/earthDiameterKm)<0.003,'Zly rozstaw planet');
 assert.match(css,/\.s3-earth-dot\{[^}]*top:116px/);
 assert.match(css,/\.s3-earth-dot\{[^}]*height:48px;width:48px/);
 assert.match(css,/\.s3-moon-dot\{[^}]*top:1581\.52px/);
 assert.match(css,/\.s3-moon-dot\{[^}]*height:13\.09px;width:13\.09px/);
 assert.match(math,/earthDiameterKm=12742/);
 assert.match(math,/s3MoonDistance:384400/);
 assert.match(math,/s3MoonSize:3474\.8/);
});
